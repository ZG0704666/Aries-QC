from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    b = p.chromium.launch(channel='msedge', headless=True)
    pg = b.new_page(viewport={'width': 1440, 'height': 1000})
    pg.goto('http://127.0.0.1:8877/', wait_until='networkidle')
    pg.wait_for_timeout(700)
    print('welcome visible', pg.is_visible('#welcome'))
    print('modal display', pg.eval_on_selector('#modal', 'e=>getComputedStyle(e).display'))
    print('overflow', pg.evaluate('document.documentElement.scrollWidth - window.innerWidth'))
    pg.click('[data-demo="merge"]')
    pg.wait_for_selector('#runView:not([hidden])', timeout=20000)
    pg.wait_for_function("() => /DONE|FAILED|NEEDS_INPUT/.test(document.querySelector('#runIdLabel').textContent)", timeout=180000)
    pg.wait_for_timeout(1200)
    print('run', pg.inner_text('#runIdLabel'))
    print('project', pg.inner_text('#projectName'))
    print('gate', pg.inner_text('#gateBadge'))
    print('kpis', pg.inner_text('#kpis').replace('\n', ' | '))
    print('headline', pg.inner_text('#headline')[:300])
    print('overflow', pg.evaluate('document.documentElement.scrollWidth - window.innerWidth'))
    pg.click('button[data-tab="classes"]')
    pg.wait_for_timeout(400)
    print('classes snippet', pg.inner_text('#tabContent')[:500].replace('\n', ' | '))
    pg.click('button[data-tab="findings"]')
    pg.wait_for_timeout(800)
    rows = pg.query_selector_all('.finding-row')
    print('finding rows', len(rows))
    row = pg.query_selector('.finding-row[data-sample]:not([data-sample=""])')
    if row:
        row.click()
        pg.wait_for_selector('#drawer:not([hidden])')
        pg.wait_for_timeout(1200)
        print('canvas', pg.eval_on_selector('#evidenceCanvas', 'e=>[e.width,e.height]'))
        print('drawer items', len(pg.query_selector_all('.evidence-item')))
        print('drawer meta', pg.inner_text('#evidenceMeta').replace('\n', ' | '))
        print('overflow drawer', pg.evaluate('document.documentElement.scrollWidth - window.innerWidth'))
    b.close()